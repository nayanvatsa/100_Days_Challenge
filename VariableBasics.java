public class variablesbasics {
    public static void main(String[] args) {
        int x;
        x = 1; 
        System.out.print(x+" ");  
        int y=5;
        System.out.println(y); 
        int m;
        m = 4;
        int n;
        n = 8;
        System.out.println(m);
        System.out.println(n);
        // modifying values of variables
        m = m+2;
        n *= 2;
        System.out.println(m);
        System.out.println(n); 
        // double float
        double p=45;
        System.out.println(p);
        p = p/2;
        System.out.println(p);
        float q=24f;
        System.out.println(q);
        q = q/7;
        System.out.println(q);
         }
}
